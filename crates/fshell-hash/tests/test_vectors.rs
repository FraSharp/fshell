use fshell_hash::{fhash256, fhash512};

const EMPTY_HASH_256: [u8; 32] = [
    0x13, 0xf6, 0xbb, 0xca, 0xb8, 0x9a, 0x18, 0xe0, 0x99, 0x1a, 0xaf, 0xb6, 0xe5, 0x8c, 0x67, 0xcb,
    0x62, 0x81, 0xa2, 0xb7, 0x96, 0x13, 0x0b, 0xde, 0x0c, 0x0a, 0x2b, 0x2f, 0x7b, 0xe5, 0x26, 0xa6,
];

const FOX_HASH_256: [u8; 32] = [
    0xb1, 0x61, 0x0e, 0x7e, 0x4e, 0xc0, 0x58, 0x40, 0x85, 0x0d, 0x59, 0x4f, 0x68, 0x89, 0x38, 0x74,
    0x93, 0xea, 0x85, 0xa0, 0x80, 0x7d, 0x59, 0x55, 0x9f, 0xdf, 0xd5, 0x41, 0x65, 0xe6, 0xbc, 0xe3,
];

const EMPTY_HASH_512: [u8; 64] = [
    0x0a, 0x69, 0xed, 0xf7, 0xd9, 0xda, 0x83, 0x80, 0xf4, 0xae, 0x92, 0xd3, 0xf5, 0x5c, 0x7b, 0x7b,
    0xc6, 0x2e, 0x17, 0xb0, 0x46, 0x6d, 0xc4, 0x94, 0x74, 0xc5, 0x12, 0xd3, 0xf4, 0x9d, 0xd7, 0x04,
    0x79, 0x4a, 0x1c, 0x5b, 0xe7, 0xa0, 0xe8, 0x60, 0x40, 0xc3, 0xfb, 0x15, 0xdf, 0xed, 0x5c, 0x46,
    0x99, 0xe5, 0x76, 0xf6, 0x54, 0xd3, 0xc3, 0x84, 0x5a, 0x7b, 0xc1, 0x5a, 0xe8, 0x35, 0x4d, 0x7f,
];

#[test]
fn test_empty_string_256() {
    assert_eq!(fhash256(b""), EMPTY_HASH_256);
}

#[test]
fn test_known_input_256() {
    assert_eq!(
        fhash256(b"The quick brown fox jumps over the lazy dog"),
        FOX_HASH_256
    );
}

#[test]
fn test_empty_string_512() {
    assert_eq!(fhash512(b""), EMPTY_HASH_512);
}

#[test]
fn test_256_is_not_prefix_of_512() {
    assert_ne!(&fhash512(b"")[..32], &fhash256(b"")[..]);
}
